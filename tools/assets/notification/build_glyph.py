#!/usr/bin/env python3
"""The update notification's small icon (v5.15): a glyph drawn for the status bar.

The maintainer, 2026-10-19: *«A – icona in alto, senza suono (consigliata)»*, and on 2026-10-19 to the round's
table, the house in the shade as well as in the status bar (*«per il resto, si a tutto»*). Until v5.15 the small
icon was the launcher's monochrome silhouette, kept on his decision of 2026-09-23 although at 24 dp its narrowest gap
is 0.71 px against the project's 2 px, because in the shade the app's name is written beside it; in the status bar,
where the notification shows its icon too, no name is. This is a glyph drawn for that size: a house -- the app's own
subject, one building -- with an arrow cut out of it pointing down, "a new version to fetch". One path, even-odd, so
the arrow is a hole the status bar's colour shows through.

**Every gap and every band 2 px or more where Android 10 draws a status-bar icon**: 17 dp, 34 px on the BV6600's
density of 2, so 1.417 px a unit of the 24-unit viewport; and at the 24 dp of the shade, 2 px a unit.
``tests/test_glyph.py`` measures it on the geometry and on a rendering.

It writes ``app/src/main/res/drawable/ic_stat_update.xml``, the VectorDrawable the notification uses. Like the
launcher's icons it is a vector in ``res/drawable/``, not a sprite of the scene, so it has no entry in
``sources/sprites.json`` (which covers ``drawable-nodpi/``): this script is its source. ``--check`` writes nothing
and fails unless the committed file is what this draws; ``--preview DIR`` writes ``ic_stat_update.svg`` and its
renderings at 34, 48 and 72 px, with the pipeline's own rasteriser.

Usage, from ``tools/assets`` with the venv's interpreter:

    python notification/build_glyph.py [--check] [--preview DIR]
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ASSETS = HERE.parent
sys.path.insert(0, str(ASSETS))

REPO = ASSETS.parent.parent
OUT = REPO / "app" / "src" / "main" / "res" / "drawable" / "ic_stat_update.xml"

#: The viewport, in units: the 24 x 24 of a Material icon.
UNITS = 24

#: The house, clockwise from the roof's apex: a roof with its eaves out past the walls.
HOUSE = [(12.0, 2.0), (22.0, 11.0), (19.5, 11.0), (19.5, 22.0), (4.5, 22.0), (4.5, 11.0), (2.0, 11.0)]
#: The arrow cut out of it: a shaft 3.5 units wide, a head 9 wide; 2 units of paper below its point.
ARROW = [(10.25, 9.0), (13.75, 9.0), (13.75, 14.0), (16.5, 14.0), (12.0, 20.0), (7.5, 14.0), (10.25, 14.0)]

#: Pixels a unit at the two sizes it is drawn at on the BV6600 (density 2): the status bar's 17 dp, the shade's 24.
PX_PER_UNIT = {"status bar (17 dp)": 34 / UNITS, "shade (24 dp)": 48 / UNITS}


def d(points) -> str:
    return "M" + " L".join(f"{x:g},{y:g}" for x, y in points) + " Z"


def vector_xml() -> str:
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- The update notification's small icon (v5.15), in the status bar and in the shade: a house with an arrow cut out
     of it, pointing down. One even-odd path: the arrow is a hole. Every gap and band is 1.6 units of 24 or more:
     2.3 px at the 17 dp Android 10 draws a status-bar icon at on a density-2 screen, 3.3 px at 24 dp.
     Generated by tools/assets/notification/build_glyph.py: edit that, not this. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24"
    android:tint="?android:attr/colorControlNormal">
    <path
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        android:pathData="{d(HOUSE)} {d(ARROW)}" />
</vector>
'''


def svg(px: int) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="0 0 {UNITS} {UNITS}">'
            f'<path d="{d(HOUSE)} {d(ARROW)}" fill="#000000" fill-rule="evenodd"/></svg>')


def segment_distance(p, a, b) -> float:
    """The distance from point p to the segment a-b."""
    (px, py), (ax, ay), (bx, by) = p, a, b
    dx, dy = bx - ax, by - ay
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def edges(poly):
    return [(poly[i], poly[(i + 1) % len(poly)]) for i in range(len(poly))]


def segments_distance(e, f) -> float:
    """The distance between two segments that do not cross: the least of each end to the other segment."""
    (a, b), (c, dd) = e, f
    return min(segment_distance(a, c, dd), segment_distance(b, c, dd), segment_distance(c, a, b), segment_distance(dd, a, b))


def narrowest() -> dict[str, float]:
    """The narrowest gap and band of the glyph, in units, by what they are.

    * paper between the hole and the outline: every vertex of one against every edge of the other;
    * the hole's own width: every pair of its edges that do not meet at a vertex;
    * the house's paper: every pair of its edges that do not meet at a vertex -- the eave, between the roof's slope
      and the wall below it, is the narrowest. Two edges that meet at a vertex close to nothing at their corner,
      which is a corner's point and not a band, so they are not paired.
    """
    out = {}
    out["paper between the arrow and the outline"] = min(
        [segment_distance(p, *e) for p in ARROW for e in edges(HOUSE)] +
        [segment_distance(p, *e) for p in HOUSE for e in edges(ARROW)])
    for name, poly in (("the arrow (hole)", ARROW), ("the house (paper)", HOUSE)):
        es = edges(poly)
        n = len(es)
        out[f"width of {name}"] = min(segments_distance(es[i], es[j]) for i in range(n) for j in range(i + 2, n)
                                      if not (i == 0 and j == n - 1))
    return out


def main(argv) -> int:
    text = vector_xml()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"stale: {OUT.relative_to(REPO)}")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    for k, g in narrowest().items():
        print(f"{k}: {g:.2f} units = " + ", ".join(f"{g * k2:.2f} px in the {name}" for name, k2 in PX_PER_UNIT.items()))
    if "--preview" in argv:
        from paperscrape_assets.raster import render_svg
        out = Path(argv[argv.index("--preview") + 1])
        out.mkdir(parents=True, exist_ok=True)
        (out / "ic_stat_update.svg").write_text(svg(UNITS))
        for px in (34, 48, 72):
            (out / f"ic_stat_update_{px}.png").write_bytes(render_svg(svg(px)).png_bytes)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

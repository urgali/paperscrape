# ------------------------------------------------------------------------------ svg plumbing
def poly(points, fill: str) -> str:
    return '<polygon points="' + " ".join(f"{x:.2f},{y:.2f}" for x, y in points) + f'" fill="{fill}"/>'


def svg_doc(width_px: int, height_px: int, view_w: float, view_h: float, comment: str, body: list[str]) -> str:
    return "\n".join(
        [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width_px}" height="{height_px}" viewBox="0 0 {view_w:g} {view_h:g}">',
         f"<!-- {comment} Generated by tools/assets/concepts/rainbird/build_rainbird_concepts.py; "
         "the wobble is written into the coordinates, nothing is computed at runtime. -->"]
        + body + ["</svg>"]
    )


def ellipse_arc(cx, cy, rx, ry, t0, t1, n):
    """Points on an ellipse from angle t0 to t1 (radians), n+1 points."""
    return [(cx + rx * math.cos(t0 + (t1 - t0) * i / n), cy + ry * math.sin(t0 + (t1 - t0) * i / n))
            for i in range(n + 1)]



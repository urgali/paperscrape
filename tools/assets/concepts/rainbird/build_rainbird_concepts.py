# Round 1 (W1-W3) failed at 1x: small thin foam marks. Round 2 is few and large, with a BODY --
# a crest of foam over a dark face -- or a motion. Every sprite is a tintable mask: a *body* mask
# is tinted with the water carried toward black, a *foam* mask with the water carried toward white.
def mound(pts_top, x0, x1, base_y, seed):
    """A wave body: the top outline ``pts_top`` from left to right, closed along ``base_y``."""
    return cut([(x0, base_y)] + list(pts_top) + [(x1, base_y)], seed, 0.4)


def lip(top_pts, under_pts, bumps, depth, seed):
    """A foam lip: a frothy upper edge over ``top_pts`` and a plain lower edge back along
    ``under_pts`` (given left to right, reversed here)."""
    return frothy(top_pts, bumps, depth, seed + "-top") + list(reversed(under_pts))



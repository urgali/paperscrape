# ------------------------------------------------------------------------------ the waves
def frothy(points, bumps: int, depth: float, seed: str):
    """The upper edge of a foam lip: the polyline ``points`` with ``bumps`` rounded bumps cut
    along it, so the crest is froth rather than a stroke."""
    out = []
    total = len(points) - 1
    for i in range(total):
        (x0, y0), (x1, y1) = points[i], points[i + 1]
        out.append((x0, y0))
        if i % max(1, total // bumps) == 0:
            for t in (0.3, 0.5, 0.7):
                bulge = depth * math.sin(math.pi * t)
                out.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t - bulge))
    out.append(points[-1])
    return cut(out, seed, 0.3)



def canopy(width: float, height: float, panels: int, scallop: float, seed: str) -> list[str]:
    """A side view of an open canopy: one half-ellipse of paper whose rim sags into a scallop
    between the ribs, with every other panel laid over it in a lighter grey, and a ferrule nub at
    the crown. The ribs run from the crown down the visible face to the rim, so a panel is a
    wedge from the crown to one scallop of the bottom edge; their feet are spaced as a dome's ribs
    project from the side, denser toward the ends."""
    cx, rim_y = width / 2, height - scallop - 0.5
    rx, ry = width / 2 - 1.0, rim_y - 3.0
    crown = (cx, 3.0)
    feet = [(cx - rx * math.cos(math.pi * k / panels), rim_y) for k in range(panels + 1)]

    def sag(a, b):
        (x0, y0), (x1, y1) = a, b
        return [(x0, y0), ((x0 * 2 + x1) / 3, y0 + scallop * 0.8), ((x0 + x1) / 2, y0 + scallop),
                ((x0 + x1 * 2) / 3, y0 + scallop * 0.8), (x1, y1)]

    top = ellipse_arc(cx, rim_y, rx, ry, math.pi, 2 * math.pi, 28)
    bottom = []
    for k in range(panels - 1, -1, -1):
        bottom += sag(feet[k], feet[k + 1])[::-1][:-1]
    out = [poly([(cx - 1.5, 0.0), (cx + 1.5, 0.0), (cx + 1.5, 3.5), (cx - 1.5, 3.5)], PAPER_3),
           poly(cut(top + bottom, f"{seed}-dome", 0.35), WHITE)]
    for k in range(1, panels, 2):
        pts = [crown] + sag(feet[k], feet[k + 1])
        out.append(poly(cut(pts, f"{seed}-{k}", 0.3), PAPER_2))
    return out



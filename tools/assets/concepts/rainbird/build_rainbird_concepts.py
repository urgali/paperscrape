def tint_stats(pixels) -> tuple[float, int]:
    import numpy as np
    a = np.asarray(pixels)
    opaque = a[..., 3] > 0
    return float(a[..., 0][opaque].mean()), int(a[..., 0][opaque].min())


def emit(family: str, name: str, svg: str, expected: tuple[int, int], scale: str, note: str, entries: list) -> None:
    out = HERE / family
    out.mkdir(parents=True, exist_ok=True)
    (out / f"{name}.svg").write_text(svg + "\n", encoding="utf-8")
    r = raster.render_svg(svg)
    if r.size != expected:
        raise SystemExit(f"{name}: rendered {r.size}, expected {expected}")
    (out / f"{name}.png").write_bytes(r.png_bytes)
    m = measure_raster(name, r)
    mean, mn = tint_stats(r.pixels)
    ok = "ok" if (mean >= 220 and mn >= 219) else "FAILS TINT CLASS"
    print(f"  {family:9s} {name:22s} {expected[0]}x{expected[1]} content {list(m.content_bbox)} "
          f"tint mean {mean:.1f} min {mn} {ok}  decoded {expected[0] * expected[1] * 4} B")
    entries.append({"name": name, "category": family, "width": expected[0], "height": expected[1],
                    "contentBox": list(m.content_bbox), "scale": scale, "tint": "TINTABLE", "usage": "concept",
                    "anchorRule": "PART_LOCAL", "anchor": [0, 0], "season": "all",
                    "source": {"kind": "svg", "file": f"{name}.svg"}, "notes": note})


def build() -> None:
    for family, table in (("bird", BIRDS), ("umbrella", UMBRELLAS), ("wave", WAVES), ("wave2", WAVES2), ("wave3", WAVES3)):
        entries: list = []
        for name, spec in table.items():
            if family == "bird":
                note, fn = spec
                svg = svg_doc(BIRD_W, BIRD_H, BIRD_W, BIRD_H, f"v4.28 bird concept: {note} Flap axis row {AXIS:g}.", fn())
                emit(family, name, svg, (BIRD_W, BIRD_H), "CANVAS_PIXELS", note + f" 51x21 CANVAS_PIXELS, flap axis row {AXIS:g}, blit origin (-25, -15).", entries)
            elif family in ("wave2", "wave3"):
                w, h, parts = spec
                svg = svg_doc(w * UNIT, h * UNIT, w, h, f"v4.28 wave concept, round 2: {name}.", parts)
                emit(family, name, svg, (w * UNIT, h * UNIT), "SCENE_UNITS", f"Round-2 wave concept {name}: {w}x{h} units, SCENE_UNITS, tintable mask (body masks tinted dark, foam masks tinted light).", entries)
                continue
            else:
                w, h, note, fn = spec
                svg = svg_doc(w * UNIT, h * UNIT, w, h, f"v4.28 {family} concept: {note}", fn())
                emit(family, name, svg, (w * UNIT, h * UNIT), "SCENE_UNITS", note + f" {w}x{h} units, SCENE_UNITS, tintable mask.", entries)
        reg = {"schemaVersion": 2, "note": f"v4.28 phase-1 {family} concepts; NOT shipped.", "sprites": entries}
        (HERE / family / "sprites.concept.json").write_text(json.dumps(reg, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    build()
